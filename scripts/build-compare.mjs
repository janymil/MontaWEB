// Builds the comparison pages from scripts/compare/competitors.mjs:
//   comparar.html (hub) and comparar/<slug>.html (one per competitor).
// Header and footer are copied from blog.html so they stay in sync with the site.
// Re-run after any data change:  node scripts/build-compare.mjs
// docs/COMPARATIVA.md explains the rules (sources, dates, D. Leg. 1044).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import * as D from './compare/competitors.mjs';

const root = new URL('../', import.meta.url);
const SITE = 'https://montaweb.pe';
const CSS_V = '20261125c';

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const jsonLd = o => JSON.stringify(o).replace(/</g, '\\u003c');

// ---- shared chrome from blog.html ----
const blog = readFileSync(new URL('blog.html', root), 'utf8').replace(/\r\n/g, '\n');
const between = (a, b) => { const i = blog.indexOf(a); const j = blog.indexOf(b, i); if (i < 0 || j < 0) throw new Error(`blog.html: missing ${a}`); return blog.slice(i, j); };
const HEADER = between('<a class="skip-link"', '<main id="contenido">').replace(' aria-current="page"', '');
const FOOTER = between('<footer class="home-footer">', '</body>');
const HEAD_ASSETS = between('<link rel="icon" type="image/svg+xml"', '<link rel="stylesheet" href="/css/blog.css');

function page({ path, title, description, ogImage, ld, body }) {
  const url = SITE + path;
  return `<!DOCTYPE html>
<html lang="es-PE" data-theme="light">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <!-- Generated by scripts/build-compare.mjs from scripts/compare/competitors.mjs. Do not edit by hand. -->
    <title>${esc(title)}</title>
    <meta name="description" content="${esc(description)}">
    <meta name="author" content="MontaWeb · Semantika TECH">
    <link rel="canonical" href="${url}">
    <meta property="og:type" content="website">
    <meta property="og:locale" content="es_PE">
    <meta property="og:site_name" content="MontaWeb">
    <meta property="og:url" content="${url}">
    <meta property="og:title" content="${esc(title)}">
    <meta property="og:description" content="${esc(description)}">
    <meta property="og:image" content="${SITE}${ogImage}">
    <meta property="og:image:width" content="1200">
    <meta property="og:image:height" content="630">
    <meta name="twitter:card" content="summary_large_image">
    ${HEAD_ASSETS}<link rel="stylesheet" href="/css/compare.css?v=${CSS_V}">
    <script type="application/ld+json">${jsonLd(ld)}</script>
</head>
<body class="site-page blog-page compare-page" data-verified-on="${D.VERIFIED_ON}" data-stale-after="${D.STALE_AFTER_DAYS}">
${HEADER}<main id="contenido">
${body}
</main>
${FOOTER}</body>
</html>
`;
}

// ---- pieces ----
const fmtDate = iso => { const [y, m, d] = iso.split('-').map(Number); return `${d} de ${D.MONTHS_ES[m - 1]} de ${y}`; };
const srcById = (c, id) => { const s = c.sources.find(x => x.id === id); if (!s) throw new Error(`${c.slug}: unknown source ${id}`); return s; };

function cellHtml(c, cell) {
  if (!cell) cell = { k: 'unlisted' };
  const label = D.CELL_LABEL[cell.k];
  const text = cell.text ? `<span class="cmp-cell__text">${esc(cell.text)}</span>` : `<span class="cmp-cell__text">${esc(label)}</span>`;
  const tag = cell.text && cell.k !== 'info' ? `<span class="cmp-tag cmp-tag--${cell.k}">${esc(label)}</span>` : '';
  const src = cell.src && c ? `<a class="cmp-src" href="${esc(srcById(c, cell.src).url)}" rel="nofollow noopener" target="_blank">fuente<span class="visually-hidden">: ${esc(srcById(c, cell.src).label)}</span></a>` : '';
  return `<div class="cmp-cell cmp-cell--${cell.k}">${tag}${text}${src}</div>`;
}

function compareTable(list, captionId, caption, rows = D.ROWS, mwCells = D.MONTAWEB.cells) {
  const cols = [{ name: 'MontaWeb', mw: true }, ...list.map(c => ({ name: c.name, c }))];
  const labels = cols.map((col, i) => `--label-${i + 2}:"${col.name.replace(/[^\p{L}\p{N} .-]/gu, '')}"`).join(';');
  const head = `<tr><th scope="col">Qué comparamos</th>${cols.map(col => `<th scope="col"${col.mw ? ' class="is-mw"' : ''}>${esc(col.name)}</th>`).join('')}</tr>`;
  const body = rows.map(r => `<tr><th scope="row">${esc(r.label)}</th>${cols.map(col => `<td${col.mw ? ' class="is-mw"' : ''}>${col.mw ? cellHtml(null, mwCells[r.id]) : cellHtml(col.c, col.c.cells[r.id])}</td>`).join('')}</tr>`).join('\n');
  const n = cols.length;
  const nth = cols.map((_, i) => `.cmp-table--n${n} td:nth-child(${i + 2})::before{content:var(--label-${i + 2})}`).join('');
  return `<div class="cmp-table-wrap" tabindex="0" role="region" aria-labelledby="${captionId}">
<table class="cmp-table cmp-table--n${n}" style='${labels}'>
<caption id="${captionId}">${esc(caption)}</caption>
<thead>${head}</thead>
<tbody>
${body}
</tbody>
</table>
</div>
<style>@container (width < 720px){${nth}}</style>`;
}

const priceNote = `<p class="cmp-note" data-price-note>Precios tal como cada empresa los publica en su propia página, revisados el ${fmtDate(D.VERIFIED_ON)}. No sumamos impuestos ni convertimos monedas. Cada plan incluye cosas distintas, así que revisa el detalle en la fuente.</p>
<p class="cmp-note cmp-note--stale" data-stale-note hidden>${esc(D.PRICES_IN_REVIEW_TEXT)}</p>`;

const factsNote = c => `<p class="cmp-note" data-price-note>Datos tal como cada empresa los publica en su propia página, revisados el ${fmtDate(D.VERIFIED_ON)}. No sumamos impuestos ni convertimos monedas. ${esc(c.noPrice)}</p>
<p class="cmp-note cmp-note--stale" data-stale-note hidden>${esc(D.PRICES_IN_REVIEW_TEXT)}</p>`;

const linkLine = l => `<p>${esc(l.before || '')}<a href="${esc(l.href)}">${esc(l.text)}</a>${esc(l.after || '')}</p>`;
const GUIDE_PATH = `/comparar/${D.GUIDE.slug}`;
const othersHtml = current => `<section class="cmp-section cmp-others"><div class="home-container"><h2>Otras comparaciones</h2><p>${D.COMPETITORS.filter(o => o !== current).map(o => `<a href="/comparar/${o.slug}">MontaWeb vs ${esc(o.name)}</a>`).join(' · ')} · <a href="/comparar">Todas en una tabla</a> · <a href="${GUIDE_PATH}">${esc(D.GUIDE.crumb)}</a></p></div></section>`;

const staleScript = `<script>
(function(){var b=document.body,v=Date.parse(b.dataset.verifiedOn+'T12:00:00-05:00'),d=+b.dataset.staleAfter;
if((Date.now()-v)/864e5>d){b.classList.add('prices-in-review');var n=document.querySelector('[data-stale-note]');if(n)n.hidden=false;}})();
</script>`;

function faqHtml(faq) {
  return `<section class="cmp-section cmp-faq" aria-labelledby="faq-title"><div class="home-container">
<h2 id="faq-title">Preguntas frecuentes</h2>
${faq.map(q => `<details><summary>${esc(q.q)}</summary><p>${esc(q.a)}</p></details>`).join('\n')}
</div></section>`;
}
const faqLd = faq => ({ '@type': 'FAQPage', mainEntity: faq.map(q => ({ '@type': 'Question', name: q.q, acceptedAnswer: { '@type': 'Answer', text: q.a } })) });
const crumbs = items => ({ '@type': 'BreadcrumbList', itemListElement: items.map(([name, path], i) => ({ '@type': 'ListItem', position: i + 1, name, item: SITE + path })) });

const cta = c => `<section class="cmp-cta"><div class="home-container">
<h2>${esc(D.CTA.title)}</h2>
<p>${esc(D.CTA.text)}</p>
<a class="button button--ink" href="${esc(D.CTA.href)}" target="_blank" rel="noopener">${esc(D.CTA.button)} <span class="button-arrow" aria-hidden="true">↗</span></a>
<a class="cmp-cta__alt" href="/servicios">Ver todos los precios de MontaWeb</a>
</div></section>`;

const trademark = `<p class="cmp-legal">${esc(D.TRADEMARK_NOTE)} <a href="mailto:hola@montaweb.pe">${esc(D.CORRECTION_TEXT)}</a></p>`;

function sourcesHtml(list) {
  return `<section class="cmp-section cmp-sources" aria-labelledby="src-title"><div class="home-container">
<h2 id="src-title">Fuentes</h2>
<ul>${list.flatMap(c => c.sources.map(s => `<li><strong>${esc(c.name)}</strong>: <a href="${esc(s.url)}" rel="nofollow noopener" target="_blank">${esc(s.label)}</a>, revisada el ${fmtDate(s.checked)}.</li>`)).join('\n')}</ul>
${trademark}
</div></section>`;
}

